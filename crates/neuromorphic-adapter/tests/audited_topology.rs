//! The contract-7 (RM-2355) and contract-8 projections the browser bridge audits.
//!
//! `src/runtime/neuromorphic-adapter.ts` compares every contract-7 and
//! contract-8 topology the WASM package exports against the constants in
//! `src/runtime/audited-topology-v7.ts` and `src/runtime/audited-topology-v8.ts`.
//! Those 288- and 512-edge arrays are generated here from the crate, never
//! typed by hand: the ignored tests write the files and the regular tests fail
//! when a committed file drifts from the crate. Regenerate with
//! `cargo test --locked --test audited_topology regenerate_audited_topology_v7 -- --ignored --exact`
//! (or `_v8`).

use neuromorphic_adapter::{
    BrowserRuntime, CONTRACT_VERSION_V7, CONTRACT_VERSION_V8, TopologySpec, encoder::EncoderMode,
};
use std::fmt::Write as _;
use std::path::PathBuf;

fn committed_path(contract: u32) -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .join(format!("../../src/runtime/audited-topology-v{contract}.ts"))
}

fn numbers<T: std::fmt::Display>(out: &mut String, name: &str, values: &[T], per_line: usize) {
    writeln!(out, "  {name}: [").unwrap();
    for line in values.chunks(per_line) {
        let joined: Vec<String> = line.iter().map(|value| value.to_string()).collect();
        writeln!(out, "    {},", joined.join(", ")).unwrap();
    }
    writeln!(out, "  ],").unwrap();
}

/// The TypeScript module for `contract`, rendered from a fresh runtime.
fn render(contract: u32) -> String {
    let spec = TopologySpec::for_contract(contract);
    let topology = BrowserRuntime::with_mode(9, EncoderMode::DEFAULT, contract)
        .expect("the audited topology is valid")
        .topology();
    assert_eq!(topology.topology_node_ids.len(), spec.neurons);
    assert_eq!(topology.topology_edge_sources.len(), spec.synapses());
    // The bridge derives node ids, edge sources and the outgoing offsets from
    // the counts (every neuron has exactly `fan_out` canonical edges), so
    // make sure that is what the projection says before writing the rest.
    assert!(
        topology
            .topology_edge_sources
            .iter()
            .enumerate()
            .all(|(edge, source)| *source as usize == edge / spec.fan_out)
    );
    assert_eq!(
        topology.topology_outgoing_edge_offsets,
        (0..=spec.neurons)
            .map(|node| (node * spec.fan_out) as u32)
            .collect::<Vec<_>>()
    );

    let issue = if contract == CONTRACT_VERSION_V7 {
        " (RM-2355)"
    } else {
        ""
    };
    let mut out = String::new();
    writeln!(
        out,
        "// Generated by `cargo test --locked --test audited_topology regenerate_audited_topology_v{contract} -- --ignored --exact`\n\
         // in crates/neuromorphic-adapter. Do not edit: `tests/audited_topology.rs` fails\n\
         // when this file drifts from the crate.\n\
         //\n\
         // The contract-{contract}{issue} `synaptic-wiring` projection the browser bridge\n\
         // audits: {} neurons with {} canonical outgoing edges each ({} synapses),\n\
         // in the adapter's canonical edge order. Node ids are `0..neurons`, edge\n\
         // `e` leaves neuron `floor(e / fanOut)`, and the outgoing offsets are\n\
         // `node * fanOut`; the bridge rebuilds those three from the counts.",
        spec.neurons,
        spec.fan_out,
        spec.synapses(),
    )
    .unwrap();
    writeln!(
        out,
        "export const AUDITED_TOPOLOGY_V{contract} = Object.freeze({{"
    )
    .unwrap();
    writeln!(out, "  contract: {contract},").unwrap();
    writeln!(out, "  digest: '{}',", topology.topology_digest).unwrap();
    writeln!(out, "  neurons: {},", spec.neurons).unwrap();
    writeln!(out, "  fanOut: {},", spec.fan_out).unwrap();
    writeln!(out, "  maxDelay: {},", spec.max_delay).unwrap();
    numbers(&mut out, "edgeTargets", &topology.topology_edge_targets, 24);
    numbers(&mut out, "edgeDelays", &topology.topology_edge_delays, 24);
    numbers(&mut out, "polarities", &topology.topology_polarities, 24);
    numbers(&mut out, "weightBits", &topology.topology_weight_bits, 8);
    out.push_str("} as const);\n");
    out
}

fn assert_committed(contract: u32) {
    let committed =
        std::fs::read_to_string(committed_path(contract)).expect("the generated module exists");
    assert_eq!(
        committed.replace("\r\n", "\n"),
        render(contract),
        "src/runtime/audited-topology-v{contract}.ts drifted; regenerate it with the ignored test"
    );
}

fn regenerate(contract: u32) {
    let path = committed_path(contract);
    std::fs::write(&path, render(contract)).expect("module is writable");
    eprintln!("wrote {}", path.display());
}

#[test]
fn the_committed_browser_projection_matches_the_crate() {
    assert_committed(CONTRACT_VERSION_V7);
}

#[test]
fn the_committed_contract8_projection_matches_the_crate() {
    assert_committed(CONTRACT_VERSION_V8);
}

#[test]
#[ignore]
fn regenerate_audited_topology_v7() {
    regenerate(CONTRACT_VERSION_V7);
}

#[test]
#[ignore]
fn regenerate_audited_topology_v8() {
    regenerate(CONTRACT_VERSION_V8);
}
